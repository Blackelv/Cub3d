#include "ft_printf.h"

int	ft_print_int(long n)
{
	int	i;

	i = 0;
	ft_putnbr_fd(n, 1);
	if (n == 0)
		return (1);
	if (n < 0)
		i++;
	while (n)
	{
		n = n / 10;
		i++;
	}
	return (i);
}
